import { afterEach, describe, expect, it, vi } from 'vitest'
import { createHttp } from '../src/api/http.js'
import { businessApp, dialogButton, documentTypes, fillPerson, input, readyPerson, submit, waitText, writes } from './businessHelpers.js'
import { click, deferred, findButton, response } from './helpers.js'

const cleanups = []
afterEach(() => { while (cleanups.length) cleanups.pop()() })
const mount = async (...args) => { const app = await businessApp(...args); cleanups.push(app.stop); return app }
async function confirm() { click(dialogButton()); await Promise.resolve() }

describe('B1 · escrituras administrativas', () => {
  it('lista cerrada de métodos/rutas y UUID limitado al manual antes de fetch', async () => {
    const fetcher = vi.fn()
    const http = createHttp(fetcher)
    for (const [path, method] of [['/personas/7','DELETE'],['/iam/usuarios/7','PATCH'],
      ['/dispositivos-edge/7/punto','PATCH'],['/personas/07/estado','PATCH'],['/otra','POST']]) {
      await expect(http.request(path,{method})).rejects.toMatchObject({ writeAttempted:false })
    }
    await expect(http.request('/personas', {method:'POST',idempotencyKey:crypto.randomUUID()})).rejects.toMatchObject({writeAttempted:false})
    await expect(http.request('/eventos-acceso/manual',{method:'POST'})).rejects.toMatchObject({writeAttempted:false})
    expect(fetcher).not.toHaveBeenCalled()
  })
  it.each(['SUPERADMIN','ADMINISTRADOR'])('Persona %s valida primero, confirma nativo y envía una sola vez ocho campos', async (role) => {
    const { fetcher, state } = await mount('/personas/nueva',role)
    await readyPerson()
    submit()
    expect(document.querySelector('dialog')).toBeNull()
    expect(writes(fetcher)).toHaveLength(0)
    fillPerson({tipo_documento:'RC'})
    submit(); submit()
    expect(document.querySelectorAll('dialog')).toHaveLength(1)
    expect(document.querySelector('dialog').open).toBe(true)
    expect(document.activeElement.textContent).toBe('Cancelar')
    const accepted = dialogButton(); click(accepted); click(accepted)
    await waitText('Referencia interna')
    expect(writes(fetcher)).toHaveLength(1)
    const options = writes(fetcher)[0][1]
    expect(Object.keys(JSON.parse(options.body))).toHaveLength(8)
    expect(options.headers['Idempotency-Key']).toBeUndefined()
    expect(state.people[100].tipo_documento).toBe('RC')
    expect(document.querySelector('input[type=file]')).toBeNull()
  })
  it.each(['cancel','escape','x'])('cerrar confirmación %s no escribe y devuelve foco', async (how) => {
    const { fetcher } = await mount('/personas/nueva')
    await readyPerson(); fillPerson(); submit()
    const dialog = document.querySelector('dialog')
    if(how==='cancel') click(dialogButton('Cancelar'))
    if(how==='escape') dialog.dispatchEvent(new Event('cancel',{cancelable:true}))
    if(how==='x') click(dialog.querySelector('[aria-label^="Cerrar"]'))
    await vi.waitFor(() => expect(findButton('Registrar Persona').disabled).toBe(false))
    expect(document.activeElement).toBe(findButton('Registrar Persona'))
    expect(writes(fetcher)).toHaveLength(0)
    expect(document.querySelector('#primer_nombre').value).toBe('Nueva')
  })
  it('Cancelar sin cambios vuelve; con cambios pregunta descartar y nunca escribe', async () => {
    const { app, fetcher } = await mount('/personas/nueva')
    await readyPerson()
    click(findButton('Cancelar'))
    expect(location.pathname).toBe('/personas')
    app.router.navigate('/personas/nueva'); await readyPerson()
    input('primer_nombre','Cambio')
    click(findButton('Cancelar'))
    expect(document.querySelector('dialog').textContent).toContain('cambios sin guardar')
    click(dialogButton('Cancelar'))
    await new Promise((resolve)=>setTimeout(resolve,0))
    expect(location.pathname).toBe('/personas/nueva')
    click(findButton('Cancelar')); click(dialogButton('Continuar y salir'))
    await vi.waitFor(() => expect(location.pathname).toBe('/personas'))
    expect(writes(fetcher)).toHaveLength(0)
  })
  it('edita solo campos cambiados, conserva histórico y permite NULL opcional', async () => {
    const { state, fetcher } = await mount('/personas/7/editar')
    await readyPerson()
    submit()
    expect(document.querySelector('dialog')).toBeNull()
    input('segundo_nombre','Segundo'); submit(); await confirm()
    await waitText('Referencia interna')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({segundo_nombre:'Segundo'})
    expect(state.people[7].id_persona).toBe(7)
    const edit = document.querySelector('a[href="/personas/7/editar"]'); click(edit)
    await readyPerson()
    input('segundo_nombre',''); submit(); await confirm(); await waitText('Referencia interna')
    expect(JSON.parse(writes(fetcher)[1][1].body)).toEqual({segundo_nombre:null})
  })
  it('legado idéntico permite editar nombre con catálogo caído; cambiar número exige tipo habilitado', async () => {
    const { app, state, fetcher } = await mount('/personas/7/editar','SUPERADMIN',{
      '/personas/7': (_u,o,s) => { if(o.method==='GET'){s.people[7].tipo_documento='PRUEBA';return response(s.people[7])} },
      '/personas/tipos-documento': () => response({error:'Caído'},503),
    })
    await waitText('Catálogo no disponible')
    input('numero_documento','OTRO'); submit()
    expect(document.querySelector('dialog')).toBeNull()
    input('numero_documento','DOC-FICTICIO'); input('primer_nombre','Cambio'); submit(); await confirm()
    await waitText('Referencia interna')
    expect(state.people[7].tipo_documento).toBe('PRUEBA')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({primer_nombre:'Cambio'})
    app.router.navigate('/personas/nueva'); await waitText('Catálogo no disponible')
    fillPerson(); submit(); expect(writes(fetcher)).toHaveLength(1)
  })
  it('ESTUDIANTE exige ID institucional y TipoPersona ACTIVO incluso en edición sin cambiarlo', async () => {
    const { fetcher } = await mount('/personas/nueva')
    await readyPerson(); fillPerson({tipo_persona:'ESTUDIANTE'}); submit()
    expect(document.querySelector('#identificador_institucional').getAttribute('aria-invalid')).toBe('true')
    expect(document.querySelector('dialog')).toBeNull()
    expect(writes(fetcher)).toHaveLength(0)
  })
  it.each([400,409,429])('rechazo confirmado %s conserva borrador y no reintenta', async (status) => {
    const {fetcher}=await mount('/personas/nueva','SUPERADMIN',{'/personas':(_u,o)=>o.method==='POST'?response({error:'Rechazo controlado'},status):undefined})
    await readyPerson();fillPerson();submit();await confirm();await waitText('Rechazo controlado')
    expect(document.querySelector('#primer_nombre').value).toBe('Nueva')
    expect(writes(fetcher)).toHaveLength(1)
    expect(findButton('Registrar Persona').disabled).toBe(false)
  })
  it.each(['network','503','invalid'])('resultado incierto %s bloquea otro envío incluso tras consultar y volver', async (kind) => {
    const {app,fetcher}=await mount('/personas/nueva','SUPERADMIN',{'/personas':(_u,o)=>{
      if(o.method!=='POST')return undefined
      if(kind==='network')return Promise.reject(new Error('Sin respuesta'))
      return kind==='503'?response({error:'No disponible'},503):response({},201)
    }})
    await readyPerson();fillPerson();submit();await confirm();await waitText('No se pudo confirmar')
    expect(findButton('Registrar Persona').disabled).toBe(true)
    submit();expect(writes(fetcher)).toHaveLength(1)
    app.router.navigate('/personas');click(dialogButton('Continuar y salir'))
    await vi.waitFor(()=>expect(location.pathname).toBe('/personas'))
    app.router.navigate('/personas/nueva');await waitText('Resultado incierto anterior')
    expect(findButton('Registrar Persona').disabled).toBe(true)
  })
  it('CSRF fallido antes de POST no clasifica escritura incierta ni pierde el borrador',async()=>{
    const {fetcher}=await mount('/personas/nueva','SUPERADMIN',{'/auth/csrf':()=>response({error:'Preflight caído'},503)})
    await readyPerson();fillPerson();submit();await confirm();await waitText('Preflight caído')
    expect(writes(fetcher)).toHaveLength(0)
    expect(findButton('Registrar Persona').disabled).toBe(false)
  })
  it('envío pendiente bloquea doble submit y navegación sin fingir rollback',async()=>{
    const pending=deferred()
    const {app,fetcher}=await mount('/personas/nueva','SUPERADMIN',{'/personas':(_u,o)=>o.method==='POST'?pending.promise:undefined})
    await readyPerson();fillPerson();submit();await confirm();submit()
    await vi.waitFor(()=>expect(writes(fetcher)).toHaveLength(1))
    app.router.navigate('/')
    expect(document.querySelector('dialog').textContent).toContain('en curso')
    click(dialogButton('Entendido'));await Promise.resolve()
    expect(location.pathname).toBe('/personas/nueva')
    expect(writes(fetcher)).toHaveLength(1)
    pending.resolve(response({},201));await waitText('No se pudo confirmar')
  })
  it.each(['ADMINISTRADOR','OPERADOR'])('IAM prohibido para %s, sin lectura o POST privilegiado',async(role)=>{
    const {fetcher}=await mount('/usuarios/nuevo',role)
    expect(document.querySelector('main').textContent).toContain('Acceso no permitido')
    expect(fetcher.mock.calls.some(([u])=>u.includes('/iam/'))).toBe(false)
  })
  it('S crea solo A/O con catálogo, confirma sin contraseña en modal y limpia campo',async()=>{
    const {fetcher}=await mount('/usuarios/nuevo')
    await vi.waitFor(()=>expect(document.querySelector('#rol').options.length).toBe(3))
    expect([...document.querySelector('#rol').options].some((o)=>o.value==='SUPERADMIN')).toBe(false)
    input('login','NUEVA_CUENTA');input('rol','OPERADOR');input('contrasena','x'.repeat(12));submit()
    expect(document.querySelector('dialog').textContent).not.toContain('x'.repeat(12))
    await confirm();await waitText('nueva_cuenta')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toMatchObject({login:'NUEVA_CUENTA',rol:'OPERADOR'})
    expect(document.querySelector('input[type=password]')).toBeNull()
  })
  it('cuenta S protegida y desactivar O se confirma mediante estado existente',async()=>{
    const {app,fetcher}=await mount('/usuarios/1')
    await waitText('super-ficticio')
    expect(findButton('Desactivar')).toBeUndefined()
    expect(findButton('Cambiar rol')).toBeUndefined()
    app.router.navigate('/usuarios/7');await waitText('operador-ficticio')
    click(findButton('Desactivar'));expect(document.querySelector('dialog').textContent).toContain('revocará sus sesiones')
    await confirm();await waitText('Operación confirmada')
    expect(writes(fetcher)[0][0]).toBe('/api/v1/iam/usuarios/7/estado')
  })
  it.each(['SUPERADMIN','ADMINISTRADOR','OPERADOR'])('Punto: estado para %s y edición/alta solo S/A',async(role)=>{
    const {fetcher}=await mount('/puntos-acceso/7',role);await waitText('Punto inactivo')
    expect(Boolean(findButton('Editar'))).toBe(role!=='OPERADOR')
    click(findButton('Activar'));await confirm();await waitText('Operación confirmada')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({estado:'ACTIVO'})
  })
  it('Punto edita solo nombre/descripción, cancela descarte y código permanece inmutable',async()=>{
    const {fetcher}=await mount('/puntos-acceso/7');await waitText('Punto inactivo')
    click(findButton('Editar'));expect(document.querySelector('input[name=codigo]')).toBeNull()
    input('nombre','Cambio');click(findButton('Cancelar edición'));click(dialogButton('Cancelar'))
    await Promise.resolve();expect(document.querySelector('#nombre').value).toBe('Cambio')
    submit();await confirm();await waitText('Operación confirmada')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({nombre:'Cambio'})
  })
  it('Dispositivo pide datos primero, selecciona Punto INACTIVO real y no inventa comunicación',async()=>{
    const {fetcher}=await mount('/dispositivos-edge/nuevo')
    await vi.waitFor(()=>expect(document.querySelector('#id_punto_acceso').options.length).toBe(3))
    expect([...document.querySelectorAll('main input,main select')].slice(0,3).map((n)=>n.name)).toEqual(['codigo','nombre','modo_operacion'])
    expect(document.querySelector('#id_punto_acceso').value).toBe('')
    input('codigo','NODO-NUEVO');input('nombre','Nodo ficticio');input('modo_operacion','ENTRADA');input('id_punto_acceso','7')
    submit();await confirm();await waitText('NODO-NUEVO')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({codigo:'NODO-NUEVO',nombre:'Nodo ficticio',modo_operacion:'ENTRADA',id_punto_acceso:7})
    expect(document.querySelector('main').textContent).toContain('INACTIVO')
  })
  it.each(['SUPERADMIN','ADMINISTRADOR','OPERADOR'])('Dispositivo %s cambia modo/estado; O no nombre',async(role)=>{
    const {fetcher}=await mount('/dispositivos-edge/7',role);await waitText('Dispositivo ficticio')
    expect(Boolean(findButton('Editar'))).toBe(role!=='OPERADOR')
    click(findButton('Cambiar modo'));input('modo_operacion','SALIDA');submit();await confirm();await waitText('Operación confirmada')
    expect(writes(fetcher)[0][0]).toBe('/api/v1/dispositivos-edge/7/modo')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({modo_operacion:'SALIDA'})
    expect(document.querySelector('input[name=id_punto_acceso],input[name=ultima_comunicacion]')).toBeNull()
  })
  it('atrás nativo con borrador pregunta sin desmontar y permite cancelar o descartar',async()=>{
    const {app}=await mount('/puntos-acceso')
    app.router.navigate('/personas/nueva');await readyPerson();fillPerson()
    history.back()
    await vi.waitFor(()=>expect(document.querySelector('dialog')).not.toBeNull())
    click(dialogButton('Cancelar'))
    await vi.waitFor(()=>expect(location.pathname).toBe('/personas/nueva'))
    expect(document.querySelector('#primer_nombre').value).toBe('Nueva')
    history.back();await vi.waitFor(()=>expect(document.querySelector('dialog')).not.toBeNull())
    click(dialogButton('Continuar y salir'))
    await vi.waitFor(()=>expect(location.pathname).toBe('/puntos-acceso'))
  })
  it('catálogo seis códigos no incluye legado como opción de alta',async()=>{
    await mount('/personas/nueva');await readyPerson()
    expect([...document.querySelector('#tipo_documento').options].slice(1).map((o)=>o.value)).toEqual(documentTypes.map((d)=>d.codigo))
  })
  it('TipoPersona inactivo no se acepta al editar aunque el cambio sea otro campo',async()=>{
    const {fetcher}=await mount('/personas/7/editar','SUPERADMIN',{
      '/personas/tipos':()=>response({tipos:[{nombre:'VISITANTE',estado:'INACTIVO'}]}),
    })
    await readyPerson();input('primer_nombre','Otro');submit()
    expect(document.querySelector('#tipo_persona').getAttribute('aria-invalid')).toBe('true')
    expect(document.querySelector('dialog')).toBeNull()
    expect(writes(fetcher)).toHaveLength(0)
  })
  it('catálogo sin habilitados bloquea alta sin inventar opciones',async()=>{
    const {fetcher}=await mount('/personas/nueva','SUPERADMIN',{
      '/personas/tipos-documento':()=>response({tipos_documento:documentTypes.map((d)=>({...d,habilitado_para_altas:false}))}),
    })
    await waitText('sin opciones habilitadas')
    expect(document.querySelector('#tipo_documento').options.length).toBe(1)
    fillPerson();submit();expect(writes(fetcher)).toHaveLength(0)
  })
  it('Punto nuevo guarda código/nombre/descripción con NULL y confirma una sola vez',async()=>{
    const {fetcher}=await mount('/puntos-acceso/nuevo')
    input('codigo','P-NUEVO');input('nombre','Punto nuevo');submit()
    expect(writes(fetcher)).toHaveLength(0)
    await confirm();await waitText('P-NUEVO')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({codigo:'P-NUEVO',nombre:'Punto nuevo',descripcion:null})
  })
  it('Dispositivo edita solo nombre, sin campos mutables de código/Punto/comunicación',async()=>{
    const {fetcher}=await mount('/dispositivos-edge/7')
    await waitText('Dispositivo ficticio');click(findButton('Editar'))
    input('nombre','Nombre nuevo');submit();await confirm();await waitText('Operación confirmada')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({nombre:'Nombre nuevo'})
    expect(writes(fetcher)[0][0]).toBe('/api/v1/dispositivos-edge/7')
  })
  it('IAM cambia solo rol asignable con catálogo y endpoint vigente',async()=>{
    const {fetcher}=await mount('/usuarios/7')
    await waitText('operador-ficticio');click(findButton('Cambiar rol'))
    await vi.waitFor(()=>expect(document.querySelector('#rol').options.length).toBe(3))
    input('rol','ADMINISTRADOR');submit();await confirm();await waitText('Operación confirmada')
    expect(writes(fetcher)[0][0]).toBe('/api/v1/iam/usuarios/7/rol')
    expect(JSON.parse(writes(fetcher)[0][1].body)).toEqual({rol:'ADMINISTRADOR'})
  })
  it('selección de Punto se conserva al paginar sin exigir búsqueda por código',async()=>{
    const {fetcher}=await mount('/dispositivos-edge/nuevo','SUPERADMIN',{
      '/puntos-acceso':(url)=>response({puntos:Number(url.searchParams.get('desplazamiento'))===0
        ?Array.from({length:20},(_,i)=>({id_punto_acceso:i+1,nombre:'Punto '+(i+1),codigo:'P'+(i+1),estado:'INACTIVO'}))
        :[{id_punto_acceso:40,nombre:'Otro Punto',codigo:'P40',estado:'ACTIVO'}]}),
    })
    await vi.waitFor(()=>expect(document.querySelector('#id_punto_acceso').options.length).toBe(21))
    input('id_punto_acceso','7');click(findButton('Página siguiente de Puntos'))
    await waitText('Página de Puntos 2')
    expect(document.querySelector('#id_punto_acceso').value).toBe('7')
    expect(document.querySelector('#codigo_punto')).toBeNull()
    expect(findButton('Buscar Punto')).toBeUndefined()
    expect(writes(fetcher)).toHaveLength(0)
  })
  it.each([401,403])('rechazo de mutación HTTP %s retira formulario y datos privilegiados',async(status)=>{
    const {app,fetcher}=await mount('/personas/nueva','SUPERADMIN',{'/personas':(_u,o)=>o.method==='POST'?response({error:'Permiso perdido'},status):undefined})
    await readyPerson();fillPerson();submit();await confirm()
    await vi.waitFor(()=>expect(app.session.getState().user).toBeNull())
    expect(document.querySelector('#numero_documento')).toBeNull()
    expect(writes(fetcher)).toHaveLength(1)
  })
  it('un error IAM no refleja credenciales aunque la respuesta las incluya',async()=>{
    await mount('/usuarios/nuevo','SUPERADMIN',{'/iam/usuarios':(_u,o)=>o.method==='POST'?response({error:'x'.repeat(12)},403):undefined})
    await vi.waitFor(()=>expect(document.querySelector('#rol').options.length).toBe(3))
    input('login','cuenta_nueva');input('rol','OPERADOR');input('contrasena','x'.repeat(12));submit();await confirm()
    await waitText('HTTP 403')
    expect(document.body.textContent).not.toContain('x'.repeat(12))
  })
})
