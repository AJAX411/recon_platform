"""Puertos de aplicación existentes."""

from typing import Protocol

from recon_platform.auditoria.dominio.evento_auditoria import EventoAuditoria
from recon_platform.integracion_edge.dominio.dispositivo_edge import DispositivoEdge


class RepositorioDispositivos(Protocol):
    def existe_codigo(self, codigo: str) -> bool: ...
    def agregar(self, dispositivo: DispositivoEdge) -> DispositivoEdge: ...
    def obtener(self, id_dispositivo: int, *, bloquear: bool = False) -> DispositivoEdge | None: ...
    def listar(self, *, limite: int, desplazamiento: int, filtros: dict) -> list[DispositivoEdge]: ...
    def actualizar(self, dispositivo: DispositivoEdge) -> DispositivoEdge: ...


class ConsultaPuntos(Protocol):
    def existe(self, id_punto: int) -> bool: ...


class Auditoria(Protocol):
    def agregar(self, evento: EventoAuditoria) -> EventoAuditoria: ...


class UnidadTrabajo(Protocol):
    def confirmar(self) -> None: ...
    def revertir(self) -> None: ...
